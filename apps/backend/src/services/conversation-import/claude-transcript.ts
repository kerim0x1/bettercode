import {
  IMPORT_LIMITS,
  type ImportedTranscript,
  type ParserOptions,
  type TranscriptParser,
} from "./types"
import {
  TranscriptBuilder,
  clampText,
  compactToolInput,
  parseJsonRecord,
  record,
  stringOf,
  stripTagBlocks,
} from "./transcript-builder"

/**
 * Reads a Claude Code session file (`<config>/projects/<folder>/<id>.jsonl`).
 *
 * Each row is one event: a `user` row holds a prompt or the results of tool
 * calls, an `assistant` row holds one content block of a reply (text,
 * thinking or a tool call), and the other rows (attachments, system notes,
 * file snapshots, titles) carry no conversation. Rows the CLI injected
 * (`isMeta`, compaction summaries, sub-agent `isSidechain` rows, local
 * command output) are left out.
 *
 * Rows link to their parent (`parentUuid`). Editing an earlier prompt or
 * rewinding starts a new branch in the same file, so an import keeps only
 * the branch that ends at the last message, as the CLI itself resumes it.
 */

type ClaudeEvent =
  | {
      kind: "prompt"
      uuid: string | null
      text: string
      /** A slash command: shown only when the assistant answered it. */
      command: boolean
      at: string
    }
  | {
      kind: "reply"
      uuid: string | null
      at: string
      model: string | null
      blocks: ReplyBlock[]
    }
  | {
      kind: "results"
      uuid: string | null
      results: Array<{ id: string | null; output: string; failed: boolean }>
    }

type ReplyBlock =
  | { type: "text"; text: string }
  | { type: "thinking"; text: string }
  | { type: "tool"; id: string | null; name: string; input: unknown }

const LOCAL_OUTPUT =
  /^<(?:local-command-stdout|local-command-stderr|local-command-caveat|bash-stdout|bash-stderr)\b/
const LOCAL_CAVEAT = "Caveat: The messages below were generated by the user"
const INTERRUPTED = /^\[Request interrupted by user/

/**
 * What a user message's text is: a prompt, a slash command (`/name args`)
 * or a shell command typed with `!`, or nothing to show (null).
 */
export function readClaudeUserText(
  raw: string
): { text: string; command: boolean } | null {
  const text = stripTagBlocks(raw, "system-reminder").trim()
  if (!text) return null
  if (text.startsWith(LOCAL_CAVEAT)) return null
  if (LOCAL_OUTPUT.test(text) || INTERRUPTED.test(text)) return null
  const name = /<command-name>([^<]*)<\/command-name>/.exec(text)?.[1]?.trim()
  if (name !== undefined) {
    if (!name) return null
    const args =
      /<command-args>([\s\S]*?)<\/command-args>/.exec(text)?.[1]?.trim() ?? ""
    const command = name.startsWith("/") ? name : `/${name}`
    return { text: args ? `${command} ${args}` : command, command: true }
  }
  const shell = /^<bash-input>([\s\S]*?)<\/bash-input>$/.exec(text)?.[1]?.trim()
  if (shell !== undefined)
    return shell ? { text: `! ${shell}`, command: true } : null
  return { text, command: false }
}

/** A tool result's text: a string, or the text blocks of a block list. */
function toolResultText(content: unknown): string {
  if (typeof content === "string") return content
  if (!Array.isArray(content)) return ""
  const parts: string[] = []
  for (const item of content) {
    const block = record(item)
    if (!block) continue
    if (block.type === "text" && typeof block.text === "string") {
      parts.push(block.text)
    } else if (block.type === "image") {
      parts.push("[Image]")
    }
  }
  return parts.join("\n")
}

export class ClaudeTranscriptParser implements TranscriptParser {
  private readonly builder: TranscriptBuilder
  private readonly events: ClaudeEvent[] = []
  /** Every row's links, to find the branch that ends at the last message. */
  private readonly links = new Map<
    string,
    {
      parent: string | null
      logical: string | null
      boundary: boolean
      /** Its place in `order`. */
      position: number
    }
  >()
  /** The rows with an id, in file order. */
  private readonly order: string[] = []
  private leaf: string | null = null
  private sessionId: string | null = null
  private cwd: string | null = null
  private pendingCommand: { text: string; at: string } | null = null

  constructor(private readonly options: ParserOptions) {
    this.builder = new TranscriptBuilder(options)
  }

  pushLine(line: string): void {
    // A listing only counts: a long line of tool results never changes the
    // count, and skipping its parse keeps large sessions quick to list.
    if (
      !this.options.keepMessages &&
      line.length > 8_192 &&
      line.includes('"tool_result"')
    ) {
      return
    }
    const row = parseJsonRecord(line)
    if (row) this.read(row)
  }

  finish(): ImportedTranscript {
    if (this.options.keepMessages) {
      const branch = this.activeBranch()
      for (const event of this.events) {
        if (!event.uuid || !branch || branch.has(event.uuid)) this.apply(event)
      }
    }
    // A command nobody answered (`/model`, `/clear`) is a setting, not a prompt.
    this.pendingCommand = null
    const built = this.builder.finish()
    return {
      provider: "claude",
      sessionId: this.sessionId,
      cwd: this.cwd,
      title: built.title,
      startedAt: built.startedAt,
      endedAt: built.endedAt,
      messages: built.messages,
      messageCount: built.messageCount,
      omittedMessages: built.omittedMessages,
      internal: false,
    }
  }

  private read(row: Record<string, unknown>): void {
    if (row.isSidechain === true) return
    this.sessionId ??= stringOf(row.sessionId)
    const uuid = stringOf(row.uuid)
    if (uuid && this.options.keepMessages) {
      // A compaction boundary has no parent; `logicalParentUuid` names the
      // row it belongs after.
      const logical = stringOf(row.logicalParentUuid)
      this.links.set(uuid, {
        parent: stringOf(row.parentUuid),
        logical,
        boundary: row.subtype === "compact_boundary" || logical !== null,
        position: this.order.length,
      })
      this.order.push(uuid)
    }
    const type = row.type
    if (type !== "user" && type !== "assistant") return
    this.cwd ??= stringOf(row.cwd)
    const at = this.builder.stamp(row.timestamp)
    const message = record(row.message)
    if (!message) return
    if (uuid) this.leaf = uuid
    const event =
      type === "user"
        ? this.readUser(row, message.content, uuid, at)
        : this.readReply(row, message, uuid, at)
    if (!event) return
    if (this.options.keepMessages) this.events.push(event)
    else this.apply(event)
  }

  private readUser(
    row: Record<string, unknown>,
    content: unknown,
    uuid: string | null,
    at: string
  ): ClaudeEvent | null {
    // Injected context, compaction summaries and transcript-only notes.
    if (
      row.isMeta === true ||
      row.isCompactSummary === true ||
      row.isVisibleInTranscriptOnly === true
    ) {
      return null
    }
    if (typeof content === "string") return this.prompt(content, uuid, at)
    if (!Array.isArray(content)) return null
    const texts: string[] = []
    let images = 0
    const results: Array<{
      id: string | null
      output: string
      failed: boolean
    }> = []
    for (const item of content) {
      const block = record(item)
      if (!block) continue
      if (block.type === "tool_result") {
        results.push({
          id: stringOf(block.tool_use_id),
          output: this.options.keepMessages
            ? clampText(
                toolResultText(block.content),
                IMPORT_LIMITS.maxToolOutputChars
              ).text
            : "",
          failed: block.is_error === true,
        })
      } else if (block.type === "text" && typeof block.text === "string") {
        texts.push(block.text)
      } else if (block.type === "image") {
        images += 1
      }
    }
    if (results.length > 0) return { kind: "results", uuid, results }
    const text = texts.join("\n\n").trim()
    if (text) return this.prompt(text, uuid, at)
    return images > 0 ? this.prompt("[Image]", uuid, at) : null
  }

  private prompt(
    raw: string,
    uuid: string | null,
    at: string
  ): ClaudeEvent | null {
    const read = readClaudeUserText(raw)
    if (!read) return null
    return {
      kind: "prompt",
      uuid,
      text: clampText(read.text, IMPORT_LIMITS.maxMessageChars).text,
      command: read.command,
      at,
    }
  }

  private readReply(
    row: Record<string, unknown>,
    message: Record<string, unknown>,
    uuid: string | null,
    at: string
  ): ClaudeEvent | null {
    if (row.isApiErrorMessage === true) return null
    const model = stringOf(message.model)
    // The CLI's own notices ("No response requested.") are not replies.
    if (model === "<synthetic>") return null
    const blocks: ReplyBlock[] = []
    const content = message.content
    if (typeof content === "string") {
      if (content.trim()) blocks.push({ type: "text", text: content })
    } else if (Array.isArray(content)) {
      for (const item of content) {
        const block = record(item)
        if (!block) continue
        if (block.type === "text" && typeof block.text === "string") {
          if (block.text.trim()) blocks.push({ type: "text", text: block.text })
        } else if (
          block.type === "thinking" &&
          typeof block.thinking === "string"
        ) {
          // Thinking the CLI shows; redacted thinking arrives empty.
          if (block.thinking.trim())
            blocks.push({ type: "thinking", text: block.thinking })
        } else if (
          block.type === "tool_use" ||
          block.type === "server_tool_use"
        ) {
          blocks.push({
            type: "tool",
            id: stringOf(block.id),
            name: stringOf(block.name) ?? "tool",
            input: this.options.keepMessages
              ? compactToolInput(block.input)
              : null,
          })
        }
      }
    }
    if (blocks.length === 0) return null
    return { kind: "reply", uuid, at, model, blocks }
  }

  private apply(event: ClaudeEvent): void {
    if (event.kind === "prompt") {
      if (event.command) {
        this.pendingCommand = { text: event.text, at: event.at }
        return
      }
      this.pendingCommand = null
      this.builder.user(event.text, event.at)
      return
    }
    if (event.kind === "results") {
      for (const result of event.results) {
        this.builder.toolResult(result.id, result.output, result.failed)
      }
      return
    }
    for (const block of event.blocks) {
      if (this.pendingCommand) {
        // A command the assistant answered (a custom prompt, `/init`).
        this.builder.user(this.pendingCommand.text, this.pendingCommand.at, {
          title: false,
        })
        this.pendingCommand = null
      }
      if (block.type === "text") {
        this.builder.assistantText(block.text, event.at, event.model)
      } else if (block.type === "thinking") {
        this.builder.reasoning(block.text, event.at, event.model)
      } else {
        this.builder.toolCall(
          { id: block.id, name: block.name, input: block.input },
          event.at,
          event.model
        )
      }
    }
  }

  /**
   * The rows on the branch that ends at the last message. Null keeps every
   * row: there is no message, or a link leads to a row this file lacks, so
   * the branch can't be told apart reliably.
   */
  private activeBranch(): Set<string> | null {
    if (!this.leaf) return null
    const branch = new Set<string>()
    let cursor: string | null = this.leaf
    while (cursor) {
      const link = this.links.get(cursor)
      // A link to a row the file lacks, or a loop: keep every row instead.
      if (!link || branch.has(cursor)) return null
      branch.add(cursor)
      if (link.parent) {
        cursor = link.parent
        continue
      }
      if (!link.boundary) break
      // A compaction boundary continues the conversation before it: the row
      // it names when that comes earlier, else (some CLI versions name a
      // later one, which would loop) the row just before it in the file.
      const logical = link.logical ? this.links.get(link.logical) : undefined
      cursor =
        link.logical && logical && logical.position < link.position
          ? link.logical
          : (this.order[link.position - 1] ?? null)
    }
    return branch
  }
}
