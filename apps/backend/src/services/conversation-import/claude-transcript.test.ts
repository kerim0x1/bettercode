import { describe, expect, it } from "vitest"
import { ClaudeTranscriptParser, readClaudeUserText } from "./claude-transcript"

// Synthetic rows in the shape Claude Code writes to
// `<config>/projects/<folder>/<session>.jsonl`.

const SESSION = "11111111-2222-4333-8444-555555555555"
const CWD = "/work/demo"

function at(second: number): string {
  return new Date(Date.UTC(2026, 2, 1, 10, 0, second)).toISOString()
}

function user(
  uuid: string,
  parent: string | null,
  content: unknown,
  second: number,
  extra: Record<string, unknown> = {}
): string {
  return JSON.stringify({
    parentUuid: parent,
    isSidechain: false,
    type: "user",
    message: { role: "user", content },
    uuid,
    timestamp: at(second),
    cwd: CWD,
    sessionId: SESSION,
    ...extra,
  })
}

function assistant(
  uuid: string,
  parent: string | null,
  block: Record<string, unknown>,
  second: number,
  extra: Record<string, unknown> = {}
): string {
  return JSON.stringify({
    parentUuid: parent,
    isSidechain: false,
    type: "assistant",
    message: {
      model: "claude-sonnet-test",
      id: `msg-${uuid}`,
      type: "message",
      role: "assistant",
      content: [block],
    },
    uuid,
    timestamp: at(second),
    cwd: CWD,
    sessionId: SESSION,
    ...extra,
  })
}

function parse(lines: string[], keepMessages = true) {
  const parser = new ClaudeTranscriptParser({ keepMessages })
  for (const line of lines) parser.pushLine(line)
  return parser.finish()
}

describe("ClaudeTranscriptParser", () => {
  it("turns a prompt and its reply into two messages with a compact tool call", () => {
    const transcript = parse([
      JSON.stringify({
        type: "permission-mode",
        permissionMode: "default",
        sessionId: SESSION,
      }),
      user("u1", null, "Fix the failing test in parser.ts", 1),
      assistant(
        "a1",
        "u1",
        {
          type: "thinking",
          thinking: "Look at the parser first.",
          signature: "sig",
        },
        2
      ),
      assistant("a2", "a1", { type: "text", text: "Let me read it." }, 3),
      assistant(
        "a3",
        "a2",
        {
          type: "tool_use",
          id: "toolu_1",
          name: "Read",
          input: {
            file_path: "/work/demo/parser.ts",
            content: "x".repeat(5_000),
          },
        },
        4
      ),
      user(
        "u2",
        "a3",
        [
          {
            type: "tool_result",
            tool_use_id: "toolu_1",
            content: "line 1\nline 2",
          },
        ],
        5,
        { toolUseResult: { stdout: "ignored" } }
      ),
      assistant(
        "a4",
        "u2",
        { type: "text", text: "Fixed: the off-by-one is gone." },
        6
      ),
      JSON.stringify({
        type: "system",
        subtype: "turn_duration",
        durationMs: 10,
        uuid: "s1",
        parentUuid: "a4",
        timestamp: at(7),
      }),
    ])

    expect(transcript.sessionId).toBe(SESSION)
    expect(transcript.cwd).toBe(CWD)
    expect(transcript.title).toBe("Fix the failing test in parser.ts")
    expect(transcript.startedAt).toBe(at(1))
    // The span of the conversation: system rows do not extend it.
    expect(transcript.endedAt).toBe(at(6))
    expect(transcript.messageCount).toBe(2)
    expect(transcript.messages).toHaveLength(2)

    const [prompt, reply] = transcript.messages
    expect(prompt).toMatchObject({
      role: "user",
      text: "Fix the failing test in parser.ts",
      createdAt: at(1),
    })
    expect(reply).toMatchObject({
      role: "assistant",
      text: "Let me read it.\n\nFixed: the off-by-one is gone.",
      reasoning: "Look at the parser first.",
      modelId: "claude-sonnet-test",
      createdAt: at(2),
    })
    expect(reply?.toolCalls).toHaveLength(1)
    const call = reply?.toolCalls?.[0]
    expect(call).toMatchObject({
      id: "toolu_1",
      name: "Read",
      output: "line 1\nline 2",
    })
    const input = call?.input as { file_path: string; content: string }
    expect(input.file_path).toBe("/work/demo/parser.ts")
    expect(input.content.length).toBeLessThan(400)
  })

  it("leaves out injected rows, local command output and sub-agent rows", () => {
    const transcript = parse([
      user(
        "m1",
        null,
        "<local-command-caveat>Caveat: generated by the user</local-command-caveat>",
        1,
        { isMeta: true }
      ),
      user(
        "c1",
        "m1",
        "<command-name>/model</command-name>\n<command-message>model</command-message>\n<command-args></command-args>",
        2
      ),
      user(
        "o1",
        "c1",
        "<local-command-stdout>Set model to Sonnet</local-command-stdout>",
        3
      ),
      user(
        "u1",
        "o1",
        "<system-reminder>Internal note</system-reminder>\nWhat does this repo do?",
        4
      ),
      assistant("x1", "u1", { type: "text", text: "Sub-agent work" }, 5, {
        isSidechain: true,
      }),
      assistant(
        "e1",
        "u1",
        { type: "text", text: "API Error: overloaded" },
        6,
        { isApiErrorMessage: true }
      ),
      assistant("a1", "u1", { type: "text", text: "It is a demo." }, 7),
      user(
        "i1",
        "a1",
        [{ type: "text", text: "[Request interrupted by user]" }],
        8
      ),
      user("k1", "i1", "Summary of the earlier conversation", 9, {
        isCompactSummary: true,
      }),
    ])

    expect(
      transcript.messages.map((message) => [message.role, message.text])
    ).toEqual([
      ["user", "What does this repo do?"],
      ["assistant", "It is a demo."],
    ])
    expect(transcript.title).toBe("What does this repo do?")
  })

  it("shows a slash command only when the assistant answered it", () => {
    const transcript = parse([
      user(
        "c1",
        null,
        "<command-name>/clear</command-name><command-args></command-args>",
        1
      ),
      user(
        "c2",
        "c1",
        "<command-name>/review</command-name><command-args>the parser</command-args>",
        2
      ),
      user("p1", "c2", "Expanded review prompt", 3, { isMeta: true }),
      assistant(
        "a1",
        "p1",
        { type: "text", text: "The parser looks fine." },
        4
      ),
    ])

    expect(
      transcript.messages.map((message) => [message.role, message.text])
    ).toEqual([
      ["user", "/review the parser"],
      ["assistant", "The parser looks fine."],
    ])
    // A command titles the chat only when nothing else does.
    expect(transcript.title).toBe("/review the parser")
  })

  it("keeps only the branch that ends at the last message after an edit", () => {
    const transcript = parse([
      user("u1", null, "First question", 1),
      assistant("a1", "u1", { type: "text", text: "First answer" }, 2),
      user("u2", "a1", "Abandoned follow-up", 3),
      assistant("a2", "u2", { type: "text", text: "Abandoned answer" }, 4),
      // The user edited the follow-up: a new branch from the first answer.
      user("u3", "a1", "Edited follow-up", 5),
      assistant("a3", "u3", { type: "text", text: "Answer to the edit" }, 6),
    ])

    expect(transcript.messages.map((message) => message.text)).toEqual([
      "First question",
      "First answer",
      "Edited follow-up",
      "Answer to the edit",
    ])
  })

  it("follows a compaction boundary through its logical parent", () => {
    const transcript = parse([
      user("u1", null, "Before compaction", 1),
      assistant("a1", "u1", { type: "text", text: "Earlier answer" }, 2),
      JSON.stringify({
        type: "system",
        subtype: "compact_boundary",
        uuid: "b1",
        parentUuid: null,
        logicalParentUuid: "a1",
        timestamp: at(3),
      }),
      user("u2", "b1", "After compaction", 4),
      assistant("a2", "u2", { type: "text", text: "Later answer" }, 5),
    ])

    expect(transcript.messages.map((message) => message.text)).toEqual([
      "Before compaction",
      "Earlier answer",
      "After compaction",
      "Later answer",
    ])
  })

  it("continues before a boundary whose logical parent comes later", () => {
    // Some CLI versions name a row after the boundary; following it would
    // loop back to the boundary.
    const transcript = parse([
      user("u1", null, "Write the parser", 1),
      assistant("a1", "u1", { type: "text", text: "Parser written." }, 2),
      JSON.stringify({
        type: "system",
        subtype: "compact_boundary",
        uuid: "b1",
        parentUuid: null,
        logicalParentUuid: "u2",
        timestamp: at(3),
      }),
      user("s1", "b1", "Summary of the earlier conversation", 4, {
        isCompactSummary: true,
      }),
      user("u2", "s1", "Continue with the tests", 5),
      assistant("a2", "u2", { type: "text", text: "Tests added." }, 6),
    ])

    expect(transcript.messages.map((message) => message.text)).toEqual([
      "Write the parser",
      "Parser written.",
      "Continue with the tests",
      "Tests added.",
    ])
  })

  it("starts the branch at a boundary that opens the file", () => {
    const transcript = parse([
      JSON.stringify({
        type: "system",
        subtype: "compact_boundary",
        uuid: "b0",
        parentUuid: null,
        logicalParentUuid: "u2",
        timestamp: at(1),
      }),
      user("s1", "b0", "Summary of the earlier session", 2, {
        isCompactSummary: true,
      }),
      user("u2", "s1", "Continue with the tests", 3),
      assistant("a2", "u2", { type: "text", text: "Tests added." }, 4),
    ])

    expect(transcript.messages.map((message) => message.text)).toEqual([
      "Continue with the tests",
      "Tests added.",
    ])
  })

  it("counts without keeping messages", () => {
    const lines = [
      user("u1", null, "One", 1),
      assistant("a1", "u1", { type: "text", text: "Two" }, 2),
      user("u2", "a1", "Three", 3),
      assistant(
        "a2",
        "u2",
        { type: "tool_use", id: "t1", name: "Bash", input: { command: "ls" } },
        4
      ),
    ]
    const counted = parse(lines, false)
    expect(counted.messages).toEqual([])
    expect(counted.messageCount).toBe(4)
    expect(counted.title).toBe("One")
    expect(parse(lines).messageCount).toBe(4)
  })

  it("skips lines that are not JSON", () => {
    const transcript = parse(["{not json", user("u1", null, "Still read", 1)])
    expect(transcript.messages).toHaveLength(1)
  })
})

describe("readClaudeUserText", () => {
  it("reads prompts, commands and shell input", () => {
    expect(readClaudeUserText("  plain prompt ")).toEqual({
      text: "plain prompt",
      command: false,
    })
    expect(
      readClaudeUserText(
        "<command-name>/init</command-name><command-args></command-args>"
      )
    ).toEqual({ text: "/init", command: true })
    expect(readClaudeUserText("<bash-input>npm test</bash-input>")).toEqual({
      text: "! npm test",
      command: true,
    })
    expect(readClaudeUserText("<bash-stdout>ok</bash-stdout>")).toBeNull()
    expect(
      readClaudeUserText("<system-reminder>only this</system-reminder>")
    ).toBeNull()
    expect(
      readClaudeUserText("[Request interrupted by user for tool use]")
    ).toBeNull()
  })
})
