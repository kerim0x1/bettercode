#!/usr/bin/env node
/**
 * Builds the phone app's WebView pages into one HTML page each, and writes
 * each as a module the app imports:
 *
 * - the code editor (apps/mobile/editor, CodeMirror 6):
 *   apps/mobile/src/editor/editor-html.ts
 * - the terminal (apps/mobile/terminal, xterm.js, as on the desktop):
 *   apps/mobile/src/terminal/terminal-html.ts
 *
 * A page is complete in itself; its Content-Security-Policy lets it load
 * nothing at all.
 *
 *   npm run mobile:pages
 *
 * The modules are committed, like the app's icons: the app and its native
 * builds need no build step for them, and scripts/mobile-pages.test.mjs
 * fails when one no longer matches its source.
 */
import fs from "node:fs"
import { createRequire } from "node:module"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { build } from "esbuild"
import * as prettier from "prettier"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const mobile = path.join(root, "apps", "mobile")
const require = createRequire(path.join(mobile, "package.json"))

/** Scripts inline and styles inline (the pages add their own); nothing else. */
export const PAGE_CSP =
  "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'"

export const PAGES = [
  {
    name: "editor",
    entry: path.join(mobile, "editor", "editor.ts"),
    module: path.join(mobile, "src", "editor", "editor-html.ts"),
    constant: "EDITOR_HTML",
    styles: [],
  },
  {
    name: "terminal",
    entry: path.join(mobile, "terminal", "terminal.ts"),
    module: path.join(mobile, "src", "terminal", "terminal-html.ts"),
    constant: "TERMINAL_HTML",
    styles: [require.resolve("@xterm/xterm/css/xterm.css")],
  },
]

export async function buildPageHtml(page) {
  const result = await build({
    entryPoints: [page.entry],
    bundle: true,
    write: false,
    format: "iife",
    minify: true,
    // The WebViews of the oldest phones the app supports (iOS 15, Android 7).
    target: ["es2020", "safari15", "chrome90"],
    legalComments: "none",
    charset: "utf8",
    logLevel: "silent",
  })
  // A "</script" inside the code would end the page's script early, and a
  // "</style" the style sheet.
  const script = result.outputFiles[0].text
    .trim()
    .replace(/<\/script/gi, "<\\/script")
  const styles = page.styles
    .map((file) => fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n").trim())
    .join("\n")
    .replace(/<\/style/gi, "<\\/style")
  return [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">',
    `<meta http-equiv="Content-Security-Policy" content="${PAGE_CSP}">`,
    `<style>html,body,#${page.name}{height:100%;margin:0;background:#0a0a0a}${styles ? `\n${styles}` : ""}</style>`,
    "</head>",
    "<body>",
    `<div id="${page.name}"></div>`,
    `<script>${script}</script>`,
    "</body>",
    "</html>",
  ].join("\n")
}

/** A page's module source, formatted as Prettier formats it. */
export async function pageModuleSource(page) {
  const html = await buildPageHtml(page)
  const source = [
    `// Generated by scripts/build-mobile-pages.mjs from apps/mobile/${page.name}.`,
    "// Do not edit; rebuild with `npm run mobile:pages`.",
    "",
    `export const ${page.constant} = ${JSON.stringify(html)}`,
    "",
  ].join("\n")
  const options = (await prettier.resolveConfig(page.module)) ?? {}
  return prettier.format(source, { ...options, filepath: page.module })
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  for (const page of PAGES) {
    const source = await pageModuleSource(page)
    fs.mkdirSync(path.dirname(page.module), { recursive: true })
    fs.writeFileSync(page.module, source)
    process.stdout.write(
      `${path.relative(root, page.module)}: ${(Buffer.byteLength(source) / 1024).toFixed(0)} KB\n`
    )
  }
}
