#!/usr/bin/env node
/**
 * Builds the phone app's code editor (apps/mobile/editor, CodeMirror 6) into
 * one HTML page, and writes it as a module the app imports:
 * apps/mobile/src/editor/editor-html.ts. The page is complete in itself;
 * its Content-Security-Policy lets it load nothing at all.
 *
 *   npm run mobile:editor
 *
 * The module is committed, like the app's icons: the app and its native
 * builds need no build step for it, and scripts/mobile-editor.test.mjs fails
 * when it no longer matches its source.
 */
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { build } from "esbuild"
import * as prettier from "prettier"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
export const EDITOR_ENTRY = path.join(root, "apps", "mobile", "editor", "editor.ts")
export const EDITOR_MODULE = path.join(root, "apps", "mobile", "src", "editor", "editor-html.ts")

/** Scripts inline and styles inline (CodeMirror adds its own); nothing else. */
export const EDITOR_CSP = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'"

export async function buildEditorHtml() {
  const result = await build({
    entryPoints: [EDITOR_ENTRY],
    bundle: true,
    write: false,
    format: "iife",
    minify: true,
    // The WebViews of the oldest phones the app supports (iOS 15, Android 7).
    target: ["es2020", "safari15", "chrome90"],
    legalComments: "none",
    charset: "utf8",
    logLevel: "silent",
  })
  // A "</script" inside the code would end the page's script early.
  const script = result.outputFiles[0].text.trim().replace(/<\/script/gi, "<\\/script")
  return [
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">',
    `<meta http-equiv="Content-Security-Policy" content="${EDITOR_CSP}">`,
    "<style>html,body,#editor{height:100%;margin:0;background:#0a0a0a}</style>",
    "</head>",
    "<body>",
    '<div id="editor"></div>',
    `<script>${script}</script>`,
    "</body>",
    "</html>",
  ].join("\n")
}

/** The module's source, formatted as Prettier formats it. */
export async function editorModuleSource() {
  const html = await buildEditorHtml()
  const source = [
    "// Generated by scripts/build-mobile-editor.mjs from apps/mobile/editor.",
    "// Do not edit; rebuild with `npm run mobile:editor`.",
    "",
    `export const EDITOR_HTML = ${JSON.stringify(html)}`,
    "",
  ].join("\n")
  const options = (await prettier.resolveConfig(EDITOR_MODULE)) ?? {}
  return prettier.format(source, { ...options, filepath: EDITOR_MODULE })
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const source = await editorModuleSource()
  fs.mkdirSync(path.dirname(EDITOR_MODULE), { recursive: true })
  fs.writeFileSync(EDITOR_MODULE, source)
  process.stdout.write(
    `${path.relative(root, EDITOR_MODULE)}: ${(Buffer.byteLength(source) / 1024).toFixed(0)} KB\n`
  )
}
